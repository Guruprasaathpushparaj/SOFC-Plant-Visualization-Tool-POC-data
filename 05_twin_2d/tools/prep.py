    i = full.get_loc(t)
    if i < PRE or i + POST >= len(full):
        continue
    a, b = sb.iloc[i - 1], sb.iloc[i]
    if (sb.iloc[i - CLEAN:i] != a).any() or (sb.iloc[i:i + CLEAN] != b).any():
        continue
