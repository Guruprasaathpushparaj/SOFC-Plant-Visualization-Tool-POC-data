def clean(s, unit):
    s = s.where(s != -1)
    if unit == "°C":
        return s.where((s > -0.5) & (s < 1300))
    return s.where(s.abs() < 1e6)

# ---- stage-border easing (same clean-border rule as tools/bends.py) ----
